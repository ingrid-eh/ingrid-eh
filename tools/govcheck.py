#!/usr/bin/env python3
"""govcheck — checks EditHealth governance records and the files they govern.

Commands
  validate              Check every record in governance/ for consistency.
  seal                  Write the steps hash into the latest change record.
  record-change         Append a change record after editing a workflow's steps.
  render                Regenerate the human-readable workflow page.
  show                  Print the workflow page to stdout.
  names NAME...         Check names against governance/naming.yaml.
  block FILE...         Check a building-block file against the workflow.

Exit status is 0 when nothing blocks, 1 when a finding blocks.
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
GOV = ROOT / "governance"
UNSEALED = "SET_BY_GOVCHECK"
GENERATED_NOTE = "<!-- Generated by `python tools/govcheck.py render`. Do not edit by hand. -->"


# ── Loading ──────────────────────────────────────────────────────────────────

def load(path: Path) -> dict:
    with path.open(encoding="utf-8") as fh:
        return yaml.safe_load(fh) or {}


@dataclass
class Registry:
    root: Path
    workflows: dict[str, tuple[Path, dict]]
    rulings: dict[str, dict]
    vocab: dict[str, list[str]]
    events: dict[str, dict]
    naming: dict

    @classmethod
    def read(cls, gov: Path = GOV) -> "Registry":
        workflows = {}
        for path in sorted((gov / "workflows").glob("*.yaml")):
            wf = load(path)
            workflows[wf["id"]] = (path, wf)
        rulings = {r["id"]: r for r in load(gov / "rulings" / "filing-rulings-index.yaml")["rulings"]}
        vocab = {k: v["values"] for k, v in load(gov / "vocabularies.yaml")["vocabularies"].items()}
        events = {e["id"]: e for e in load(gov / "events.yaml")["events"]}
        naming = load(gov / "naming.yaml")
        return cls(gov.parent, workflows, rulings, vocab, events, naming)


# ── Findings ─────────────────────────────────────────────────────────────────

@dataclass
class Findings:
    items: list[tuple[str, str, str]] = field(default_factory=list)

    def block(self, where: str, msg: str) -> None:
        self.items.append(("BLOCK", where, msg))

    def warn(self, where: str, msg: str) -> None:
        self.items.append(("WARN", where, msg))

    @property
    def blocking(self) -> bool:
        return any(level == "BLOCK" for level, _, _ in self.items)

    def report(self, title: str) -> str:
        if not self.items:
            return f"{title}: no findings."
        lines = [f"{title}: {len(self.items)} finding(s)", "", "| Level | Where | Finding |", "|---|---|---|"]
        lines += [f"| {lvl} | {where} | {msg} |" for lvl, where, msg in self.items]
        return "\n".join(lines)


# ── Workflow helpers ─────────────────────────────────────────────────────────

def steps_sha256(steps: list) -> str:
    canonical = json.dumps(steps, sort_keys=True, ensure_ascii=False, default=str)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def semver(v: str) -> tuple[int, int, int]:
    m = re.fullmatch(r"(\d+)\.(\d+)\.(\d+)", str(v))
    if not m:
        raise ValueError(f"not a version: {v!r}")
    return tuple(int(x) for x in m.groups())  # type: ignore[return-value]


def bump(v: str, part: str) -> str:
    major, minor, patch = semver(v)
    if part == "major":
        return f"{major + 1}.0.0"
    if part == "minor":
        return f"{major}.{minor + 1}.0"
    return f"{major}.{minor}.{patch + 1}"


def current_version(wf: dict) -> str:
    return wf["changes"][-1]["version"]


def page_path(wf_path: Path) -> Path:
    return wf_path.with_suffix(".md")


# ── validate ─────────────────────────────────────────────────────────────────

def check_vocab(f: Findings, reg: Registry, where: str, vocab: str, value) -> None:
    if value is None:
        return
    if value not in reg.vocab.get(vocab, []):
        f.block(where, f"{value!r} is not in vocabulary {vocab} {reg.vocab.get(vocab)}")


def validate_rulings(f: Findings, reg: Registry) -> None:
    id_re = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
    for rid, r in reg.rulings.items():
        where = f"ruling {rid}"
        if not id_re.match(rid):
            f.block(where, "ID is not a semantic kebab-case label")
        check_vocab(f, reg, where, "change-domain", r.get("domain"))
        check_vocab(f, reg, where, "standing", r.get("standing"))
        if r.get("standing") == "ruled" and not r.get("ruled_by"):
            f.block(where, "standing is ruled but ruled_by is empty")
        if not r.get("source"):
            f.block(where, "no source")


def validate_workflow(f: Findings, reg: Registry, wf_path: Path, wf: dict) -> None:
    wid = wf["id"]
    id_re = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
    seen: set[str] = set()
    for step in wf.get("steps", []):
        sid = step.get("id", "?")
        where = f"{wid} step {sid}"
        if sid in seen:
            f.block(where, "duplicate step ID")
        seen.add(sid)
        if not id_re.match(sid):
            f.block(where, "step ID is not a semantic kebab-case label")
        for key in ("name", "level", "standing", "does"):
            if not step.get(key):
                f.block(where, f"missing {key}")
        check_vocab(f, reg, where, "standing", step.get("standing"))
        check_vocab(f, reg, where, "name-standing", step.get("name_standing"))
        check_vocab(f, reg, where, "step-level", step.get("level"))
        if step.get("name_standing") == "minted":
            f.warn(where, f"step name {step['name']!r} is minted; needs Ingrid's smart name")
        if step.get("check") is None:
            f.warn(where, "step has no check")
        for rid in step.get("rulings", []):
            if rid not in reg.rulings:
                f.block(where, f"cites ruling {rid!r}, which is not in the rulings index")
        for eid in step.get("events", []):
            if eid not in reg.events:
                f.block(where, f"sets off event {eid!r}, which is not in events.yaml")

    # Rulings that carry a machine check.
    step_ids = [s["id"] for s in wf.get("steps", [])]
    for rid in {r for s in wf.get("steps", []) for r in s.get("rulings", [])}:
        enforce = reg.rulings.get(rid, {}).get("enforce") or {}
        last = enforce.get("last_step")
        if last and step_ids and step_ids[-1] != last:
            f.block(f"{wid}", f"ruling {rid}: {last!r} must be the last step; last is {step_ids[-1]!r}")

    # Change records: every change to the steps is recorded.
    changes = wf.get("changes") or []
    if not changes:
        f.block(wid, "no change records")
        return
    ids = [c.get("id") for c in changes]
    if len(ids) != len(set(ids)):
        f.block(wid, "duplicate change record IDs")
    try:
        versions = [semver(c["version"]) for c in changes]
        if versions != sorted(versions) or len(set(versions)) != len(versions):
            f.block(wid, "change record versions do not strictly increase")
    except (KeyError, ValueError) as exc:
        f.block(wid, f"bad change record version: {exc}")
    for c in changes:
        where = f"{wid} change {c.get('id')}"
        check_vocab(f, reg, where, "standing", c.get("standing"))
        if c.get("standing") == "ruled" and not c.get("ruled_by"):
            f.block(where, "standing is ruled but ruled_by is empty")
        for sid in c.get("steps_affected", []) or []:
            if sid not in step_ids:
                f.warn(where, f"names step {sid!r}, which is not in the current workflow")
    latest = changes[-1]
    recorded = latest.get("steps_sha256")
    actual = steps_sha256(wf.get("steps", []))
    if recorded == UNSEALED:
        f.block(wid, "latest change record is not sealed; run `python tools/govcheck.py seal`")
    elif recorded != actual:
        f.block(
            wid,
            "the steps changed since the last change record. Record the change: "
            "`python tools/govcheck.py record-change --summary ... --bump minor`",
        )

    # The human-readable page is in step with the record.
    page = page_path(wf_path)
    if not page.exists() or page.read_text(encoding="utf-8") != render_workflow(wf, reg):
        f.block(str(page.relative_to(reg.root)), "page is out of date; run `python tools/govcheck.py render`")


def cmd_validate(reg: Registry) -> Findings:
    f = Findings()
    validate_rulings(f, reg)
    for wf_path, wf in reg.workflows.values():
        validate_workflow(f, reg, wf_path, wf)
    return f


# ── seal / record-change ─────────────────────────────────────────────────────

def cmd_seal(reg: Registry) -> int:
    sealed = 0
    for wf_path, wf in reg.workflows.values():
        text = wf_path.read_text(encoding="utf-8")
        if UNSEALED in text:
            wf_path.write_text(text.replace(UNSEALED, steps_sha256(wf["steps"])), encoding="utf-8")
            sealed += 1
            print(f"sealed {wf_path.relative_to(reg.root)}")
    if not sealed:
        print("nothing to seal")
    return 0


def yaml_scalar(value) -> str:
    """One YAML scalar on one line, quoted when needed."""
    return yaml.safe_dump(value, default_flow_style=True, allow_unicode=True, width=10_000).strip().removesuffix("...").strip()


def cmd_record_change(reg: Registry, args) -> int:
    wf_path, wf = reg.workflows[args.workflow]
    latest = wf["changes"][-1]
    actual = steps_sha256(wf["steps"])
    if latest.get("steps_sha256") == actual and not args.no_step_change:
        print("The steps have not changed since the last change record. "
              "Edit the steps first, or pass --no-step-change for a change outside the steps.", file=sys.stderr)
        return 1
    standing = args.standing or ("ruled" if args.ruled_by else "proposed")
    if standing not in reg.vocab["standing"]:
        print(f"standing must be one of {reg.vocab['standing']}", file=sys.stderr)
        return 1
    date = args.date or dt.date.today().isoformat()
    version = bump(current_version(wf), args.bump)
    slug = args.id or re.sub(r"[^a-z0-9]+", "-", args.summary.lower()).strip("-")[:60].rstrip("-")
    cid = slug if slug.startswith("chg-") else f"chg-{date}-{slug}"
    entry = {
        "id": cid,
        "version": version,
        "date": date,
        "ruled_by": args.ruled_by,
        "standing": standing,
        "summary": args.summary,
        "steps_affected": args.steps or [],
        "source": {"box_file_id": args.box_file_id, "file": args.source},
        "steps_sha256": actual,
    }
    lines = [f"  - id: {yaml_scalar(entry['id'])}"]
    for key in ("version", "date", "ruled_by", "standing", "summary", "steps_affected", "source", "steps_sha256"):
        lines.append(f"    {key}: {yaml_scalar(entry[key])}")
    text = wf_path.read_text(encoding="utf-8")
    if not text.endswith("\n"):
        text += "\n"
    wf_path.write_text(text + "\n".join(lines) + "\n", encoding="utf-8")
    reg = Registry.read(reg.root / "governance")
    wf_path, wf = reg.workflows[args.workflow]
    page_path(wf_path).write_text(render_workflow(wf, reg), encoding="utf-8")
    print(f"recorded {cid} as version {version}; page regenerated")
    return 0


# ── render ───────────────────────────────────────────────────────────────────

def cell(value) -> str:
    if value is None or value == [] or value == "":
        return "—"
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def render_workflow(wf: dict, reg: Registry) -> str:
    out = [
        GENERATED_NOTE,
        "",
        f"# {wf['title']}",
        "",
        f"Version {current_version(wf)} · Owner: {wf['owner']} · Standing: {wf['standing']} · Pilot: {wf.get('pilot', '—')}",
        "",
        f"Applies to: {wf['applies_to']}. Building blocks are written to `{wf.get('output_folder', '—')}`.",
        "",
        "Step names marked † are minted and wait for a smart name.",
        "",
        "## Steps",
        "",
        "| Step | Level | Standing | Writes | Check | Sets off |",
        "|---|---|---|---|---|---|",
    ]
    for s in wf["steps"]:
        name = s["name"] + (" †" if s.get("name_standing") == "minted" else "")
        out.append(
            f"| **{cell(name)}** | {cell(s['level'])} | {cell(s['standing'])} | {cell(s.get('output'))} "
            f"| {cell(s.get('check'))} | {cell(', '.join(s.get('events', [])))} |"
        )
    out += ["", "## What each step does", ""]
    for s in wf["steps"]:
        out.append(f"### {s['name']}")
        out.append("")
        out.append(cell(s["does"]))
        rulings = s.get("rulings") or []
        if rulings:
            out.append("")
            out.append("Rulings applied:")
            out.append("")
            for rid in rulings:
                r = reg.rulings.get(rid, {})
                who = f"{r.get('ruled_by')}, {r.get('date')}" if r.get("ruled_by") else f"{r.get('standing', '?')}"
                out.append(f"- `{rid}` — {cell(r.get('ruling', 'NOT IN INDEX'))} ({who})")
        ev = s.get("evidence") or {}
        if ev:
            run = ev.get("run") or "not yet run"
            out.append("")
            out.append(f"Evidence: {ev.get('file')} (Box {ev.get('box_file_id')}), run {run}.")
        out.append("")
    out += ["## Open items", "", "| Item | Question |", "|---|---|"]
    for item in wf.get("open_items", []):
        out.append(f"| {cell(item['id'])} | {cell(item['question'])} |")
    out += ["", "## Change history", "", "| Version | Date | Change | Ruled by | Standing | Steps |", "|---|---|---|---|---|---|"]
    for c in wf["changes"]:
        out.append(
            f"| {cell(c['version'])} | {cell(c['date'])} | {cell(c['summary'])} | {cell(c.get('ruled_by'))} "
            f"| {cell(c.get('standing'))} | {cell(', '.join(c.get('steps_affected') or []))} |"
        )
    out.append("")
    return "\n".join(out)


def cmd_render(reg: Registry) -> int:
    for wf_path, wf in reg.workflows.values():
        page_path(wf_path).write_text(render_workflow(wf, reg), encoding="utf-8")
        print(f"rendered {page_path(wf_path).relative_to(reg.root)}")
    return 0


# ── names ────────────────────────────────────────────────────────────────────

def check_names(reg: Registry, names: list[str], as_pattern: str | None = None) -> Findings:
    f = Findings()
    patterns = {p["id"]: re.compile(p["regex"]) for p in reg.naming["patterns"]}
    for name in names:
        matched = [pid for pid, rx in patterns.items() if rx.fullmatch(name)]
        for rule in reg.naming.get("forbidden", []):
            if any(pid in rule.get("exempt", []) for pid in matched):
                continue
            if re.search(rule["regex"], name, flags=re.IGNORECASE):
                f.block(name, f"{rule['id']}: {rule['reason']}")
        if as_pattern:
            if as_pattern not in patterns:
                f.block(name, f"unknown pattern {as_pattern!r}")
            elif as_pattern not in matched:
                example = next(p["example"] for p in reg.naming["patterns"] if p["id"] == as_pattern)
                f.block(name, f"does not match {as_pattern} (example: {example})")
        elif not matched:
            f.warn(name, "matches no naming pattern")
    return f


# ── block ────────────────────────────────────────────────────────────────────

STEP_LINE = re.compile(r"workflow step:?\s*\*\*(?P<name>[^*]+)\*\*", re.IGNORECASE)
CHECK_RESULT = re.compile(r"^#+\s*Check\b|^Result:|\bcheck (passes|fails)\b", re.IGNORECASE | re.MULTILINE)
VOCAB_FIELDS = ("placement", "lock")
INLINE_FIELD = re.compile(r"\b(Placement|Lock):\s*([^.|\n]+)")


def vocab_findings(reg: Registry, name: str, text: str) -> list[tuple[str, str, str]]:
    """Placement and lock values, inline ("Lock: hard") and in table columns headed Placement or Lock."""
    values: list[tuple[str, str]] = [(field.lower(), value) for field, value in INLINE_FIELD.findall(text)]
    columns: dict[int, str] = {}
    for line in text.splitlines():
        if not line.lstrip().startswith("|"):
            columns = {}
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if all(re.fullmatch(r":?-{3,}:?", c) for c in cells if c):
            continue
        if not columns and any(c.lower() in VOCAB_FIELDS for c in cells):
            columns = {i: c.lower() for i, c in enumerate(cells) if c.lower() in VOCAB_FIELDS}
            continue
        values += [(field, cells[i]) for i, field in columns.items() if i < len(cells)]
    f = Findings()
    for field, value in values:
        value = value.strip().strip("*").strip()
        if not value or value in {"—", "-"}:
            continue
        allowed = [v.lower() for v in reg.vocab[field]]
        if not any(value.lower().startswith(v) for v in allowed):
            f.block(name, f"{field} value {value!r} does not start with a value in vocabulary {reg.vocab[field]}")
    return f.items


def check_block(reg: Registry, path: Path, workflow: str = "WF-template-creation") -> Findings:
    f = Findings()
    _, wf = reg.workflows[workflow]
    text = path.read_text(encoding="utf-8")
    name = path.name
    by_name = {s["name"].lower(): s for s in wf["steps"]}

    m = STEP_LINE.search(text)
    step = None
    if m:
        step = by_name.get(m.group("name").strip().lower())
        if step is None:
            f.block(name, f"names workflow step {m.group('name')!r}, which is not in {workflow}. "
                          "If the workflow changed, record the change first.")
    else:
        # Fall back to the file's suffix: the first step that writes a file of this kind.
        for s in wf["steps"]:
            outputs = [p.strip().split(" ")[0] for p in str(s.get("output") or "").split(";") if p.strip()]
            if any(name.endswith(o.replace("<LABEL>", "")) for o in outputs):
                step = s
                break
        if step is None:
            f.warn(name, "no 'Workflow step:' line and no step writes a file of this kind")
        elif step.get("name_standing") == "recorded":
            f.warn(name, f"no 'Workflow step:' line; expected **{step['name']}**")

    if step:
        outputs = [p.strip().split(" ")[0] for p in str(step.get("output") or "").split(";") if p.strip()]
        rx = [re.compile("^" + re.escape(o).replace(re.escape("<LABEL>"), r"[A-Z0-9]+(?:-[A-Z0-9]+)+") + "$") for o in outputs]
        if rx and not any(r.match(name) for r in rx):
            f.block(name, f"step {step['name']!r} writes {', '.join(outputs)}; this file is named {name}")
        if step.get("check") and not CHECK_RESULT.search(text):
            f.warn(name, f"step {step['name']!r} has a check; the file records no check result "
                         "(a 'Check' heading, a 'Result:' line, or 'the check passes')")

    f.items.extend(vocab_findings(reg, name, text))
    f.items.extend(check_names(reg, [name]).items)
    return f


# ── CLI ──────────────────────────────────────────────────────────────────────

def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gov", type=Path, default=GOV, help="governance folder (default: repo governance/)")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("validate")
    sub.add_parser("seal")
    sub.add_parser("render")
    show = sub.add_parser("show")
    show.add_argument("--workflow", default="WF-template-creation")
    rc = sub.add_parser("record-change")
    rc.add_argument("--workflow", default="WF-template-creation")
    rc.add_argument("--summary", required=True, help="What changed, in one sentence")
    rc.add_argument("--ruled-by", help="Who ruled the change (blank = proposed)")
    rc.add_argument("--standing", help="ruled, proposed or observed")
    rc.add_argument("--date", help="YYYY-MM-DD (default today)")
    rc.add_argument("--steps", nargs="*", help="Step IDs the change affects")
    rc.add_argument("--source", help="File or conversation where the ruling is recorded")
    rc.add_argument("--box-file-id")
    rc.add_argument("--id", help="Change ID (default from the summary)")
    rc.add_argument("--bump", choices=["major", "minor", "patch"], default="minor")
    rc.add_argument("--no-step-change", action="store_true", help="Record a change that leaves the steps as they are")
    nm = sub.add_parser("names")
    nm.add_argument("names", nargs="*", help="Names to check (default: one per line on stdin)")
    nm.add_argument("--as", dest="as_pattern", help="Require this naming pattern ID")
    bl = sub.add_parser("block")
    bl.add_argument("files", nargs="+", type=Path)
    bl.add_argument("--workflow", default="WF-template-creation")
    args = ap.parse_args(argv)

    reg = Registry.read(args.gov)
    if args.cmd == "validate":
        f = cmd_validate(reg)
        print(f.report("govcheck validate"))
        return 1 if f.blocking else 0
    if args.cmd == "seal":
        return cmd_seal(reg)
    if args.cmd == "render":
        return cmd_render(reg)
    if args.cmd == "show":
        _, wf = reg.workflows[args.workflow]
        print(render_workflow(wf, reg))
        return 0
    if args.cmd == "record-change":
        return cmd_record_change(reg, args)
    if args.cmd == "names":
        names = args.names or [line.strip() for line in sys.stdin if line.strip()]
        f = check_names(reg, names, args.as_pattern)
        print(f.report("govcheck names"))
        return 1 if f.blocking else 0
    if args.cmd == "block":
        f = Findings()
        for path in args.files:
            f.items.extend(check_block(reg, path, args.workflow).items)
        print(f.report("govcheck block"))
        return 1 if f.blocking else 0
    return 2


if __name__ == "__main__":
    sys.exit(main())
